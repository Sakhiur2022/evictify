#!/usr/bin/env python3
"""Build bio.c for every (policy, lookup, NBUF) on the host, run a matrix of
workloads, cross-check every run against refmodel.py, and write CSV + Markdown.

usage: python3 run_matrix.py [--quick] [--out DIR]
Env: CC (default gcc).  No QEMU needed; bio.c is compiled unmodified.
"""
import os, subprocess, sys, tempfile, shutil, csv, itertools
import refmodel
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.dirname(HERE)
CC = os.environ.get("CC", "gcc")
POL = {"LRU": "-DBCACHE_LRU", "CLOCK": "", "CLOCK-NR": "-DBCACHE_CLOCK_NOREF_ON_LOAD"}
WNAME = {0: "toy", 1: "seq", 2: "hotscan", 3: "wset", 4: "pollute", 5: "mixed", 6: "safety"}

def build(tmp, pol, lookup, nbuf):
    exe = os.path.join(tmp, f"sim_{pol}_{lookup}_{nbuf}")
    flags = POL[pol].split() + (["-DBCACHE_LOOKUP_HASH"] if lookup == "hash" else [])
    cmd = [CC, "-w", "-O1", *flags, f"-DNBUF={nbuf}", "-I" + tmp, "-I" + HERE, "-I" + SRC,
           "-o", exe, os.path.join(tmp, "bio.c"), os.path.join(HERE, "stubs.c"),
           os.path.join(HERE, "main.c")]
    subprocess.run(cmd, check=True)
    return exe

def run(exe, cfg):
    out = subprocess.run([exe, *map(str, cfg)], capture_output=True, text=True)
    if out.returncode != 0:
        raise RuntimeError(f"{exe} {cfg}: {out.stderr or out.stdout[-300:]}")
    hdr = row = None
    for l in out.stdout.splitlines():
        if l.startswith("CSVH,"): hdr = l.split(",")[1:]
        if l.startswith("CSV,"): row = l.split(",")[1:]
    return dict(zip(hdr, row))

def main():
    quick = "--quick" in sys.argv
    outdir = sys.argv[sys.argv.index("--out") + 1] if "--out" in sys.argv else os.path.join(SRC, "..")
    nbufs = [30, 60, 90]
    # (workload, scan, hot, interval, passes, rounds)
    cfgs = [(0, 1, 1, 1, 1, 1), (6, 1, 1, 1, 1, 1)]
    scans = [40, 120, 240] if not quick else [120]
    for sc in scans:
        cfgs += [(1, sc, 4, 40, 3, 5),
                 (2, sc, 4, 40, 3, 5),
                 (4, sc, 8, 40, 3, 5),
                 (5, sc, 8, 40, 3, 5)]
    for hot in ([8, 24, 48] if not quick else [24]):
        cfgs.append((3, 1, hot, 40, 3, 5))
    cfgs += [(2, 120, 4, 40, 3, 5), (2, 120, 4, 20, 3, 5), (2, 120, 4, 60, 3, 5)]
    cfgs = list(dict.fromkeys(cfgs))
    tmp = tempfile.mkdtemp(); shutil.copy(os.path.join(SRC, "bio.c"), tmp)
    rows = []; bad = 0
    try:
        for nbuf in nbufs:
            exes = {(p, l): build(tmp, p, l, nbuf) for p in POL for l in ("list", "hash")}
            for cfg in cfgs:
                for (p, l), exe in exes.items():
                    r = run(exe, cfg); rows.append(r)
                    # cross-check against the independent model
                    if cfg[0] in (0, 1, 2, 3, 4, 5):   # safety (6) pins buffers: checked in-kernel instead
                        m = refmodel.simulate(p, nbuf, refmodel.gen(cfg[0], nbuf, *cfg[1:5], cfg[5]), cfg[2])
                        pairs = [("hits", "hits"), ("misses", "misses"), ("hot_req", "hot_req"), ("hot_hits", "hot_hits"),
                                 ("vic_insp", "vic_insp"), ("hot_evict", "hot_evict"),
                                 ("ws_probes", "ws_probes"), ("ws_res", "ws_res")]
                        if p == "LRU": pairs.append(("lru_ptrw", "lru_ptrw"))
                        else: pairs += [("ref_clears", "ref_clears"), ("ref_checks", "ref_checks"),
                                        ("ref_set_hit", "ref_set_hit")]
                        if l == "list": pairs.append(("lookup_insp", "lookup_insp"))
                        pairs += [("requests", "requests")]
                        for ck, mk in pairs:
                            if cfg[0] == 6 and ck in ("hits",): pass
                            if int(r[ck]) != m[mk]:
                                bad += 1
                                print(f"MISMATCH {p}/{l} nbuf={nbuf} cfg={cfg} {ck}: C={r[ck]} model={m[mk]}")
        # fairness: identical request sequence & count per config
        for key in {(r["nbuf"], r["workload"], r["scan"], r["hot"], r["interval"], r["passes"], r["rounds"]) for r in rows}:
            grp = [r for r in rows if (r["nbuf"], r["workload"], r["scan"], r["hot"], r["interval"], r["passes"], r["rounds"]) == key]
            assert len({(r["seqhash"], r["requests"]) for r in grp}) == 1, key
    finally:
        shutil.rmtree(tmp)
    os.makedirs(outdir, exist_ok=True)
    cols = list(rows[0].keys())
    with open(os.path.join(outdir, "results.csv"), "w", newline="") as f:
        w = csv.DictWriter(f, cols); w.writeheader(); w.writerows(rows)
    write_md(rows, os.path.join(outdir, "results.md"), bad)
    print(f"{len(rows)} runs, {bad} model mismatches -> {outdir}/results.csv, results.md")
    sys.exit(1 if bad else 0)

def write_md(rows, path, bad):
    I = lambda r, k: int(r[k])
    L = ["# Buffer cache: LRU (default) vs Clock\n",
         "Generated by `bcsim/run_matrix.py` from the unmodified `bio.c` (host build, no QEMU).",
         f"Cross-check against the independent Python model (`bcsim/refmodel.py`): **{bad} mismatches**.",
         "Same request sequence, cold start and unit costs for every policy (sequence checksum asserted equal).",
         "Cost units: miss 4000us, hit 10us, inspect 1us, bookkeeping write 1us. All numbers are modeled, not wall-clock.\n",
         "Policies: `LRU` = default xv6; `CLOCK` = second chance, B_REF set on load; `CLOCK-NR` = second chance, B_REF set only on re-reference.",
         "Lookup: `list` = original xv6 list scan; `hash` = policy-independent hash lookup (isolates the replacement policy).\n"]
    keys = sorted({(I(r,"nbuf"), I(r,"workload"), I(r,"scan"), I(r,"hot"), I(r,"interval"), I(r,"passes"), I(r,"rounds")) for r in rows},
                  key=lambda k: (k[1], k[0], k[2], k[3], k[4]))
    for lk in ("hash", "list"):
        L += [f"## Lookup = {lk}\n",
              "| NBUF | workload | scan | hot | intv | policy | hit% | hot-hit% | retention% | misses | hot evict | lookup us | replace us | I/O+hit us | total us | Δ total vs LRU | Δ I/O+hit | Δ lookup | Δ replace |",
              "|--:|---|--:|--:|--:|---|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|"]
        for k in keys:
            if k[1] in (0, 6): continue
            g = {r["policy"]: r for r in rows if r["lookup"] == lk and
                 (I(r,"nbuf"), I(r,"workload"), I(r,"scan"), I(r,"hot"), I(r,"interval"), I(r,"passes"), I(r,"rounds")) == k}
            base = g["LRU"]
            for p in ("LRU", "CLOCK", "CLOCK-NR"):
                r = g[p]
                pct = lambda a, b: f"{100*I(r,a)/I(r,b):.1f}" if I(r, b) else "-"
                io = I(r,"io_us") + I(r,"hit_us"); bio = I(base,"io_us") + I(base,"hit_us")
                d = lambda a, b_: "" if p == "LRU" else f"{a-b_:+d}"
                L.append(f"| {k[0]} | {WNAME[k[1]]} | {k[2]} | {k[3]} | {k[4]} | {p} | {pct('hits','requests')} | {pct('hot_hits','hot_req')} | {pct('ws_res','ws_probes')} | {r['misses']} | {r['hot_evict']} | {r['lookup_us']} | {r['repl_us']} | {io} | {r['total_us']} | "
                         f"{d(I(r,'total_us'), I(base,'total_us'))} | {d(io, bio)} | {d(I(r,'lookup_us'), I(base,'lookup_us'))} | {d(I(r,'repl_us'), I(base,'repl_us'))} |")
        L.append("")
    open(path, "w").write("\n".join(L) + "\n")

if __name__ == "__main__":
    main()
